// Package durable 将 Pulse 的可靠完整节点检查点保存到独占 Store 会话。
//
// Graph 仍是可复用定义；Run/Resume 每次创建独立 Execution。Resume 重供输入并核对
// 业务版本、静态拓扑、真实类型对应的 Codec ID/版本和输入编码指纹。只有确认的完整成果
// 才恢复，未确认节点从业务函数开头重新进入；不恢复 Go 调用栈或外部副作用。
//
// 内置 Retry 的游标与子图作用域一起持久化：活跃尝试可以认回，失败祖先使其后代失效。
// 根尝试只有一次完整运行预算；最终真实失败后，Resume 不补发 Retry 次数。
// Store/Codec/恢复回调失败或宿主取消留下活跃尝试，本次停止，Resume 重读权威记录。
//
// MemoryStore 仅验证协议；进程退出恢复应使用真正持久后端，如 filestore。
// 外部副作用仍由宿主通过幂等键、事务、去重或 outbox 处理。本库不承诺 exactly-once，
// 受管流的消息、来源游标、读取确认、显式状态及消息预算保存为格式 2 的纯数据。
// 活跃来源需显式声明可按位置续读；已完成来源可恢复未确认尾部。普通格式 1 仍可读取。
// 不支持原生 channel 值、持久等待或分布式执行管理。
package durable
